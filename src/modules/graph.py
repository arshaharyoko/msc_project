def build_adjacency_matrices(device):
    """Return the (3, 25, 25) relation adjacency tensor."""
    return torch.tensor(ADJACENCY_LISTS).float().to(device)


def load_node_features(embeddings_path, device):
    """Return (protein_features, node_features) as raw 1024-D tensors.

    ``protein_features`` is the 21 ProtT5 rows; ``node_features`` appends the
    four abstract rows. The static-then-trainable row order matters: the models
    slice at ``graph_n_static`` to split the frozen buffer from the learnable
    parameter.
    """
    gen = torch.Generator(device="cpu").manual_seed(ABSTRACT_SEED)

    with open(embeddings_path) as f:
        embeddings = json.load(f)

    protein_features = torch.tensor(
        [embeddings[accession] for accession in NODE_ACCESSIONS], dtype=torch.float32
    ).to(device)
    abstract_features = torch.randn(
        N_ABSTRACT, protein_features.size(1), generator=gen
    ).to(device)
    node_features = torch.cat([protein_features, abstract_features], dim=0)

    return protein_features, node_features
